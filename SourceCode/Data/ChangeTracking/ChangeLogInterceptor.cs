using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Diagnostics;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Storage;
using Microsoft.Extensions.Logging;
using System.Runtime.CompilerServices;

namespace ModulesRegistry.Data.ChangeTracking;

/// <summary>
/// Writes one <see cref="ChangeLog"/> row per added, changed or deleted entity, in the same transaction as the save
/// (Migration step 2C.5c). Register it after <see cref="SkipUnchangedValuesInterceptor"/>, so only real changes are logged.
/// </summary>
/// <remarks>
/// <para>
/// The rows are written right after the save, since an added entity's key is generated by the database. When the caller
/// has no transaction, one is started before the save and committed after the rows are written; a failing log write
/// rolls back the whole save. A caller's own transaction is used and left to the caller.
/// </para>
/// <para>
/// Only entities with a single <see cref="int"/> key are logged. Retention: rows beyond
/// <see cref="ChangeLogOptions.MaxRowsPerObject"/> for a saved object are deleted in the same transaction; rows older than
/// <see cref="ChangeLogOptions.MaxAgeDays"/> at most once a day (<see cref="ChangeLogCleanupSchedule"/>), after the save (a failure there is logged, not thrown).
/// </para>
/// <para>Scoped: one instance per circuit or request, since <see cref="ICurrentUser"/> is.</para>
/// </remarks>
public sealed class ChangeLogInterceptor(ICurrentUser currentUser, ChangeLogOptions options, ChangeLogCleanupSchedule cleanupSchedule, TimeProvider timeProvider, ILogger<ChangeLogInterceptor> logger) : SaveChangesInterceptor
{
    private const int AgeCleanupBatchSize = 500;
    private readonly ConditionalWeakTable<DbContext, PendingSave> _pendingSaves = new();

    public override InterceptionResult<int> SavingChanges(DbContextEventData eventData, InterceptionResult<int> result)
    {
        BeforeSaveAsync(eventData.Context, isAsync: false, default).GetAwaiter().GetResult();
        return result;
    }

    public override async ValueTask<InterceptionResult<int>> SavingChangesAsync(DbContextEventData eventData, InterceptionResult<int> result, CancellationToken cancellationToken = default)
    {
        await BeforeSaveAsync(eventData.Context, isAsync: true, cancellationToken);
        return result;
    }

    public override int SavedChanges(SaveChangesCompletedEventData eventData, int result)
    {
        AfterSaveAsync(eventData.Context, isAsync: false, default).GetAwaiter().GetResult();
        return result;
    }

    public override async ValueTask<int> SavedChangesAsync(SaveChangesCompletedEventData eventData, int result, CancellationToken cancellationToken = default)
    {
        await AfterSaveAsync(eventData.Context, isAsync: true, cancellationToken);
        return result;
    }

    public override void SaveChangesFailed(DbContextErrorEventData eventData) =>
        AbandonAsync(eventData.Context, isAsync: false).GetAwaiter().GetResult();

    public override Task SaveChangesFailedAsync(DbContextErrorEventData eventData, CancellationToken cancellationToken = default) =>
        AbandonAsync(eventData.Context, isAsync: true);

    public override void SaveChangesCanceled(DbContextEventData eventData) =>
        AbandonAsync(eventData.Context, isAsync: false).GetAwaiter().GetResult();

    public override Task SaveChangesCanceledAsync(DbContextEventData eventData, CancellationToken cancellationToken = default) =>
        AbandonAsync(eventData.Context, isAsync: true);

    private async Task BeforeSaveAsync(DbContext? context, bool isAsync, CancellationToken cancellationToken)
    {
        if (context is null) return;
        if (_pendingSaves.TryGetValue(context, out var pending) && pending.IsWritingLog) return;

        var changes = context.ChangeTracker.Entries()
            .Where(e => e.State is EntityState.Added or EntityState.Modified or EntityState.Deleted && IsLogged(e.Metadata))
            .Select(ToPendingChange)
            .OfType<PendingChange>()
            .ToList();
        if (changes.Count == 0) return;

        IDbContextTransaction? ownTransaction = null;
        if (context.Database.CurrentTransaction is null)
        {
            ownTransaction = isAsync ?
                await context.Database.BeginTransactionAsync(cancellationToken) :
                context.Database.BeginTransaction();
        }
        _pendingSaves.AddOrUpdate(context, new PendingSave(changes, ownTransaction));
    }

    private async Task AfterSaveAsync(DbContext? context, bool isAsync, CancellationToken cancellationToken)
    {
        if (context is null || !_pendingSaves.TryGetValue(context, out var pending) || pending.IsWritingLog) return;
        try
        {
            pending.IsWritingLog = true;
            var userId = await currentUser.GetUserIdAsync();
            var changedAt = timeProvider.GetUtcNow();
            var rows = pending.Changes.Select(c => c.ToChangeLog(userId, changedAt)).ToList();
            context.Set<ChangeLog>().AddRange(rows);
            if (isAsync) await context.SaveChangesAsync(cancellationToken); else context.SaveChanges();

            foreach (var savedObject in rows.Select(r => (r.EntityType, r.EntityId)).Distinct())
            {
                await DeleteRowsBeyondMaxAsync(context, savedObject.EntityType, savedObject.EntityId, isAsync, cancellationToken);
            }

            if (pending.OwnTransaction is not null)
            {
                if (isAsync) await pending.OwnTransaction.CommitAsync(cancellationToken); else pending.OwnTransaction.Commit();
            }
        }
        finally
        {
            await AbandonAsync(context, isAsync);
        }
        await DeleteRowsPastAgeAsync(context, isAsync, cancellationToken);
    }

    /// <summary>
    /// Forgets the save and disposes an own transaction (a rollback unless committed). Called when the save fails, and
    /// after the log is written. When the log's own save fails, this runs first from <see cref="SaveChangesFailed"/>,
    /// and the call from <see cref="AfterSaveAsync"/> finds nothing left.
    /// </summary>
    private async Task AbandonAsync(DbContext? context, bool isAsync)
    {
        if (context is null || !_pendingSaves.TryGetValue(context, out var pending)) return;
        _pendingSaves.Remove(context);
        if (pending.OwnTransaction is null) return;
        if (isAsync) await pending.OwnTransaction.DisposeAsync(); else pending.OwnTransaction.Dispose();
    }

    private async Task DeleteRowsBeyondMaxAsync(DbContext context, string entityType, int entityId, bool isAsync, CancellationToken cancellationToken)
    {
        var expired = context.Set<ChangeLog>()
            .Where(c => c.EntityType == entityType && c.EntityId == entityId)
            .OrderByDescending(c => c.Id)
            .Skip(options.MaxRowsPerObject)
            .Select(c => c.Id);
        var ids = isAsync ? await expired.ToListAsync(cancellationToken) : expired.ToList();
        if (ids.Count == 0) return;
        var rows = context.Set<ChangeLog>().Where(c => ids.Contains(c.Id));
        if (isAsync) await rows.ExecuteDeleteAsync(cancellationToken); else rows.ExecuteDelete();
    }

    /// <summary>
    /// The oldest rows first, by id (ids follow time), compared in memory, since SQLite can't compare <see cref="DateTimeOffset"/>.
    /// </summary>
    private async Task DeleteRowsPastAgeAsync(DbContext context, bool isAsync, CancellationToken cancellationToken)
    {
        var now = timeProvider.GetUtcNow();
        if (!cleanupSchedule.TryClaim(now)) return;
        try
        {
            var cutoff = now.AddDays(-options.MaxAgeDays);
            while (true)
            {
                var oldest = context.Set<ChangeLog>().OrderBy(c => c.Id).Take(AgeCleanupBatchSize).Select(c => new { c.Id, c.ChangedAt });
                var batch = isAsync ? await oldest.ToListAsync(cancellationToken) : oldest.ToList();
                var ids = batch.TakeWhile(c => c.ChangedAt < cutoff).Select(c => c.Id).ToList();
                if (ids.Count == 0) break;
                var rows = context.Set<ChangeLog>().Where(c => ids.Contains(c.Id));
                if (isAsync) await rows.ExecuteDeleteAsync(cancellationToken); else rows.ExecuteDelete();
                if (ids.Count < batch.Count) break;
            }
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            logger.CleanupFailed(ex, options.MaxAgeDays);
        }
    }

    private static bool IsLogged(IEntityType entityType) =>
        entityType.ClrType != typeof(ChangeLog) &&
        !entityType.IsOwned() &&
        entityType.FindPrimaryKey() is { Properties: [{ ClrType: var keyType }] } && keyType == typeof(int);

    private static PendingChange? ToPendingChange(EntityEntry entry)
    {
        var keyName = entry.Metadata.FindPrimaryKey()!.Properties[0].Name;
        return entry.State switch
        {
            EntityState.Added => new PendingChange(entry, keyName, ChangeOperation.Added, null),
            EntityState.Deleted => new PendingChange(entry, keyName, ChangeOperation.Deleted, null),
            EntityState.Modified when entry.ModifiedProperties() is { IsModified: true } modified =>
                new PendingChange(entry, keyName, ChangeOperation.Modified, string.Join(',', modified.Select(p => p.Metadata.Name))),
            _ => null,
        };
    }

    private sealed class PendingSave(List<PendingChange> changes, IDbContextTransaction? ownTransaction)
    {
        public List<PendingChange> Changes { get; } = changes;
        public IDbContextTransaction? OwnTransaction { get; } = ownTransaction;
        public bool IsWritingLog { get; set; }
    }

    /// <param name="Entry">Read after the save: an added entity's key is generated by the database.</param>
    private sealed record PendingChange(EntityEntry Entry, string KeyName, ChangeOperation Operation, string? ChangedProperties)
    {
        public ChangeLog ToChangeLog(int? userId, DateTimeOffset changedAt) => new()
        {
            EntityType = Truncate(Entry.Metadata.ClrType.Name, ChangeLogExtensions.EntityTypeMaxLength)!,
            EntityId = (int)Entry.Property(KeyName).CurrentValue!,
            Operation = Operation,
            ChangedProperties = Truncate(ChangedProperties, ChangeLogExtensions.ChangedPropertiesMaxLength),
            UserId = userId,
            ChangedAt = changedAt,
        };

        private static string? Truncate(string? value, int maxLength) =>
            value is null || value.Length <= maxLength ? value : value[..maxLength];
    }
}